#include <stdio.h>

int main() {
    // 1. เติม Escape character เพื่อขึ้นบรรทัดใหม่ (\n)
    printf("Line 1: Computer Programming\n");
    
    // 2. เติม Escape character เพื่อขึ้นบรรทัดใหม่ (\n)
    printf("Line 2: Language C\n");
    
    // 3 & 4. เติม Escape character เพื่อเว้นระยะแท็บ (\t)
    printf("Column 1\tColumn 2\tColumn 3\n");
    
    return 0;
}
